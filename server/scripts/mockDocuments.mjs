/**
 * Mock project documents for demonstration (npm run seed:sample).
 * Each PDF uses the system's report layout and is clearly marked "SAMPLE – FOR DEMONSTRATION ONLY":
 * the content is made up from the project's own record, it is not an official DPWH document.
 */
import { COLORS, Report, fmt } from '../src/services/pdfLayout.js';

const BY = 'IPMATS sample data (seed:sample)';
const WARNING = 'SAMPLE – FOR DEMONSTRATION ONLY. This document was generated by the IPMATS demo seed from the project record. It is not an official DPWH, contractor or COA document.';

function toBuffer(report) {
  return new Promise((resolve, reject) => {
    const chunks = [];
    report.doc.on('data', (c) => chunks.push(c));
    report.doc.on('end', () => resolve(Buffer.concat(chunks)));
    report.doc.on('error', reject);
    report.end();
  });
}

const where = (p) => `${p.barangay_name ? `Barangay ${p.barangay_name}, ` : ''}${p.municipality_name}, Occidental Mindoro`;

function start(p, docType, reference) {
  const r = new Report({ title: p.name, docType, reference, subtitle: where(p), generatedBy: BY, meta: [['Project ID', p.project_code], ['Document', 'Sample']] });
  r.note(WARNING);
  return r;
}

/** Contract agreement between the implementing office and the contractor. */
export async function contractAgreement(p) {
  const r = start(p, 'CONTRACT AGREEMENT (SAMPLE)', `CA-${p.project_code}`);
  r.section('Parties');
  r.keyValue([
    ['Procuring entity', p.agency_name],
    ['Contractor', p.contractor_name || 'To be awarded'],
    ['Contract reference', p.contract_ref_no || `CA-${p.project_code}`],
    ['Fund source', p.fund_source],
  ]);
  r.section('Contract terms');
  r.keyValue([
    ['Approved budget (ABC)', fmt.peso(p.approved_budget)],
    ['Contract amount', fmt.peso(p.contract_amount)],
    ['Notice to Proceed', fmt.date(p.notice_to_proceed)],
    ['Contract duration', p.duration_days ? `${p.duration_days} calendar days` : '—'],
    ['Target completion', fmt.date(p.target_completion_date)],
    ['Location', where(p)],
  ]);
  r.section('Scope of work');
  r.paragraph(p.description || p.name);
  r.paragraph('The contractor shall furnish all labor, materials, equipment and supervision needed to complete the works according to the approved plans, the Program of Work and the DPWH Standard Specifications, and shall keep the site safe for the public during construction.');
  r.signatures([
    { label: 'For the procuring entity', name: 'District Engineer (sample)' },
    { label: 'For the contractor', name: 'Authorized representative (sample)' },
  ]);
  return toBuffer(r);
}

/** Program of Work: the phases, their weights and schedule, and the cost per phase. */
export async function programOfWork(p, phases) {
  const r = start(p, 'PROGRAM OF WORK (SAMPLE)', `POW-${p.project_code}`);
  r.section('Construction phases');
  const total = Number(p.contract_amount || p.approved_budget || 0);
  r.table(
    [
      { header: '#', width: 0.4, value: (x) => String(x.sequence_no) },
      { header: 'Phase', width: 3, value: (x) => x.name },
      { header: 'Weight', width: 0.9, align: 'right', value: (x) => fmt.pct(x.weight, 0) },
      { header: 'Planned start', width: 1.3, value: (x) => fmt.date(x.planned_start) },
      { header: 'Planned end', width: 1.3, value: (x) => fmt.date(x.planned_end) },
      { header: 'Estimated cost', width: 1.7, align: 'right', value: (x) => fmt.peso((total * Number(x.weight)) / 100) },
    ],
    phases,
  );
  r.section('Summary');
  r.keyValue([
    ['Approved budget (ABC)', fmt.peso(p.approved_budget)],
    ['Contract amount', fmt.peso(p.contract_amount)],
    ['Duration', p.duration_days ? `${p.duration_days} calendar days` : '—'],
    ['Implementing office', p.agency_name],
  ]);
  r.signatures([
    { label: 'Prepared by', name: 'Project Engineer (sample)' },
    { label: 'Approved by', name: 'District Engineer (sample)' },
  ]);
  return toBuffer(r);
}

/** Progress report: physical accomplishment per phase as of the report date. */
export async function progressReport(p, phases, { number = 1, reportDate, remarks } = {}) {
  const r = start(p, `PROGRESS REPORT NO. ${number} (SAMPLE)`, `PR-${p.project_code}-${String(number).padStart(2, '0')}`);
  r.kpis([
    { label: 'Report date', value: fmt.date(reportDate) },
    { label: 'Work accomplished', value: fmt.pct(p.overall_progress) },
    { label: 'Planned as of today', value: fmt.pct(p.planned_progress) },
    { label: 'Status', value: fmt.label(p.status) },
  ]);
  r.section('Accomplishment by phase');
  r.table(
    [
      { header: 'Phase', width: 3, value: (x) => `${x.sequence_no}. ${x.name}` },
      { header: 'Weight', width: 0.9, align: 'right', value: (x) => fmt.pct(x.weight, 0) },
      { header: 'Accomplished', width: 1.2, align: 'right', value: (x) => fmt.pct(x.accomplishment) },
      { header: 'Contributes', width: 1.2, align: 'right', value: (x) => fmt.pct((Number(x.weight) * Number(x.accomplishment)) / 100, 2) },
    ],
    phases,
  );
  r.section('Remarks from the site');
  r.paragraph(remarks || 'Work is ongoing according to the Program of Work. No major issue reported.');
  r.signatures([
    { label: 'Prepared by', name: 'Project Engineer (sample)' },
    { label: 'Noted by', name: 'Chief, Construction Section (sample)' },
  ]);
  return toBuffer(r);
}

/** Inspection report with a site photo. */
export async function inspectionReport(p, { inspectionDate, photo, findings = [] } = {}) {
  const r = start(p, 'INSPECTION REPORT (SAMPLE)', `IR-${p.project_code}-${String(inspectionDate || '').replace(/-/g, '')}`);
  r.section('Inspection details');
  r.keyValue([
    ['Date of inspection', fmt.date(inspectionDate)],
    ['Location', where(p)],
    ['Coordinates', `${Number(p.latitude).toFixed(6)}, ${Number(p.longitude).toFixed(6)}`],
    ['Work accomplished', fmt.pct(p.overall_progress)],
  ]);
  if (photo) {
    const w = r.width;
    const h = w * 0.62;
    r.ensureSpace(h + 70); // keep the heading with the photo
    r.section('Site photo');
    const y = r.y;
    r.doc.image(photo, r.left, y, { fit: [w, h], align: 'center', valign: 'center' });
    r.y = y + h + 6;
    r.font('Body', 7.8, COLORS.muted).text('Concreted road with the box culvert under construction beside the walkway (photo supplied for the demo).', r.left, r.y, { width: w });
    r.y += 16;
  }
  r.section('Observations');
  for (const f of findings) r.paragraph(`• ${f}`);
  r.signatures([
    { label: 'Inspected by', name: 'Project Inspector (sample)' },
    { label: 'Noted by', name: 'District Engineer (sample)' },
  ]);
  return toBuffer(r);
}

/** Disbursement voucher for a payment to the contractor. */
export async function disbursementVoucher(p, { amount, date: payDate, reference, purpose }) {
  const r = start(p, 'DISBURSEMENT VOUCHER (SAMPLE)', reference);
  r.kpis([
    { label: 'Amount', value: fmt.peso(amount) },
    { label: 'Date', value: fmt.date(payDate) },
    { label: 'Payee', value: p.contractor_name || '—' },
    { label: 'Reference', value: reference },
  ]);
  r.section('Particulars');
  r.paragraph(purpose);
  r.keyValue([
    ['Contract amount', fmt.peso(p.contract_amount)],
    ['Fund source', p.fund_source],
    ['Implementing office', p.agency_name],
  ]);
  r.signatures([
    { label: 'Certified by (accounting)', name: 'Accountant (sample)' },
    { label: 'Approved by', name: 'District Engineer (sample)' },
  ]);
  return toBuffer(r);
}
