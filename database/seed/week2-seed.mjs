const PH = [];
const PU = [];
const FR = [];
const PROG = [];
const q = (v) => (v === null || v === undefined ? 'null' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const pid = (code) => `(select id from public.projects where project_code = ${q(code)})`;
const submitter = (code) =>
  `(select pr.id from public.profiles pr where pr.email = (select case when a.code = 'DPWH-SJFO' then 'personnel.south@dpwh360.local' else 'personnel@dpwh360.local' end from public.projects p join public.agencies a on a.id = p.agency_id where p.project_code = ${q(code)}))`;
const min = (a, b) => (a < b ? a : b);

/** Planned % on a date from the phase windows (same idea as computePlannedProgress). */
function plannedAt(phases, date) {
  const d = toDate(date);
  return phases.reduce((s, p) => {
    const st = toDate(p.planned_start);
    const en = toDate(p.planned_end);
    const f = d < st ? 0 : d >= en ? 1 : (d - st) / (en - st);
    return s + p.weight * f;
  }, 0);
}

/** Spread an overall % over the phases in order (earlier phases finish first). */
function fill(phases, overall) {
  let left = overall;
  return phases.map((p) => {
    const take = Math.max(0, Math.min(p.weight, left));
    left -= take;
    return round2((take / p.weight) * 100);
  });
}

const out = [
  '-- WEEK 2 sample data (generated by database/seed/week2-seed.mjs; fictional amounts and progress)',
  `-- today = ${TODAY}`,
  'begin;',
  `delete from public.progress_updates  where project_id in (select id from public.projects where project_code in (${PROJECTS.map((p) => q(p[0])).join(', ')}));`,
  `delete from public.financial_records where project_id in (select id from public.projects where project_code in (${PROJECTS.map((p) => q(p[0])).join(', ')}));`,
  `delete from public.project_phases    where project_id in (select id from public.projects where project_code in (${PROJECTS.map((p) => q(p[0])).join(', ')}));`,
];

for (const [code, type, ntp, days, target, actualDone, contract, pace, extra = {}] of PROJECTS) {
  const phases = planFromTemplate(type, ntp, days);
  const done = Boolean(actualDone);
  const end = done ? actualDone : TODAY;

  // Monthly report dates from NTP + 30 days until today (or the completion date)
  const reportDates = [];
  for (let d = addDays(ntp, 30); d <= end && d <= TODAY; d = addDays(d, 30)) reportDates.push(d);
  if (done && reportDates.at(-1) !== actualDone) reportDates.push(actualDone);

  const accStart = phases.map(() => null);
  const accEnd = phases.map(() => null);
  let prev = 0;
  let accomp = phases.map(() => 0);
  const reports = [];
  reportDates.forEach((date, i) => {
    let overall = done && i === reportDates.length - 1 ? 100 : Math.min(99, plannedAt(phases, date) * pace);
    overall = round2(Math.max(prev, overall));
    prev = overall;
    accomp = fill(phases, overall);
    accomp.forEach((a, k) => {
      if (a > 0 && !accStart[k]) accStart[k] = phases[k].planned_start <= date ? phases[k].planned_start : date;
      if (a >= 100 && !accEnd[k]) accEnd[k] = date;
    });
    const computed = computeOverallProgress(phases.map((p, k) => ({ weight: p.weight, accomplishment: accomp[k] })));
    reports.push({ date, overall: computed, snapshot: phases.map((p, k) => ({ sequence_no: p.sequence_no, name: p.name, weight: p.weight, accomplishment: accomp[k] })) });
  });

  phases.forEach((p, k) => PH.push(`(${q(code)},${p.sequence_no},${q(p.name)},${p.weight},${q(p.planned_start)},${q(p.planned_end)},${q(accStart[k])},${q(accEnd[k])},${accomp[k]})`));
  reports.forEach((r, i) => {
    const remarks = done && i === reports.length - 1 ? 'All phases completed; final inspection done.' : pace < 0.85 && i === reports.length - 1 ? 'Behind schedule; contractor to submit a catch-up plan.' : null;
    PU.push(`(${q(code)},${q(r.date)},${r.overall},'{${r.snapshot.map((x) => x.accomplishment).join(',')}}',${q(remarks)})`);
  });
  const finalOverall = reports.at(-1)?.overall ?? 0;
  PROG.push(`(${q(code)},${finalOverall})`);

  // ---- Financial records ----
  const fin = [];
  const rec = (type, amount, date, ref, desc) => date <= TODAY && fin.push({ type, amount: round2(amount), date, ref, desc });
  rec('obligation', contract, min(addDays(ntp, -10), TODAY), `OB-${code}-01`, 'Obligation of the full contract amount');
  let revised = contract;
  if (extra.vo) {
    const voDate = addDays(ntp, Math.round(days * 0.45));
    if (voDate <= TODAY) {
      rec('variation_order', contract * extra.vo, voDate, `VO-${code}-01`, extra.vo > 0 ? 'Additional slope protection works' : 'Deletion of unused drainage items');
      revised = round2(contract + contract * extra.vo);
      if (extra.vo > 0) rec('obligation', contract * extra.vo, voDate, `OB-${code}-02`, 'Obligation for variation order no. 1');
    }
  }
  let paid = 0;
  rec('disbursement', revised * 0.15, addDays(ntp, 14), `DV-${code}-01`, '15% advance payment');
  if (addDays(ntp, 14) <= TODAY) paid = round2(revised * 0.15);
  let n = 2;
  reports.forEach((r, i) => {
    if (i % 2 === 1 || i === reports.length - 1) {
      // Progress billing: paid up to 90% of the work done (10% retention); "aheadPayments" pays faster than the work
      const due = extra.aheadPayments ? Math.min(0.95, r.overall / 100 + 0.25) : (r.overall / 100) * 0.9;
      const amount = round2(revised * due - paid);
      if (amount > revised * 0.02) {
        rec('disbursement', amount, addDays(r.date, 7) <= TODAY ? addDays(r.date, 7) : r.date, `DV-${code}-${String(n).padStart(2, '0')}`, `Progress billing no. ${n - 1} (${r.overall}% accomplished)`);
        paid = round2(paid + amount);
        n += 1;
      }
    }
  });
  if (done) {
    const retentionDate = addDays(actualDone, 30);
    if (retentionDate <= TODAY && revised - paid > 0) rec('disbursement', revised - paid, retentionDate, `DV-${code}-${String(n).padStart(2, '0')}`, 'Final payment and release of retention');
  }
  if (reports.length) rec('expense', 85000, addDays(ntp, 20), `EX-${code}-01`, 'Materials quality testing');
  if (reports.length > 3) rec('expense', 25000, addDays(ntp, 45), `EX-${code}-02`, 'Project information billboard');

  for (const f of fin) FR.push(`(${q(code)},${q(f.type)},${f.amount},${q(f.ref)},${q(f.date)},${q(f.desc)})`);
  const disbursed = round2(fin.filter((f) => f.type === 'disbursement').reduce((s, f) => s + f.amount, 0));
  if (disbursed > revised + 0.01) throw new Error(`${code}: disbursed ${disbursed} > revised ${revised}`);
}
